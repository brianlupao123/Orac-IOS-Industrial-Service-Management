#!/usr/bin/env node
// UX ratchet: counts style violations per file and refuses to let any count go up.
//   node scripts/ux-ratchet.mjs                check against ux/baseline.json (exit 1 on any increase)
//   node scripts/ux-ratchet.mjs --init         create ux/baseline.json from today's code (first run only)
//   node scripts/ux-ratchet.mjs --update       lock in improvements (counts may only go down)
//   node scripts/ux-ratchet.mjs --report       progress table: every rule, baseline, current, target, worst files
//   node scripts/ux-ratchet.mjs --json         machine-readable result (used by ux-trace)
//   node scripts/ux-ratchet.mjs --rule TYP-XS  limit to one rule
// Rules live in ux/rules.json. No dependencies.
import fs from "node:fs";
import path from "node:path";
import { ROOT, readJson, writeJson, walk } from "./ux-lib.mjs";

const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const only = args.includes("--rule") ? args[args.indexOf("--rule") + 1] : null;
const cfg = readJson("ux/rules.json");
const files = cfg.scan.dirs.flatMap((d) => walk(d, cfg.scan.exts));
const guarded = new Set(cfg.guarded || []);
const basePath = "ux/baseline.json";
const baseline = fs.existsSync(path.join(ROOT, basePath)) ? readJson(basePath) : null;

const transfers = cfg.transfers || [];
// credit: how much rule `to` may rise in file f, earned by cutting a `from` rule in the same file
const credit = (to, f, cur) => Math.max(0, ...transfers.filter((t) => t.to === to).map((t) => (baseline?.rules[t.from]?.files?.[f] || 0) - (cur[t.from] ? (cur[t.from].files[f] || 0) : (baseline?.rules[t.from]?.files?.[f] || 0))));

const current = {}; // rule -> { total, files: {file: n}, lines: {file: [line,...]} }
for (const r of cfg.rules) {
  if (only && r.id !== only) continue;
  const re = new RegExp(r.regex, "g");
  const rec = { total: 0, files: {}, lines: {} };
  for (const f of files) {
    if (r.exceptFiles?.includes(f)) continue;
    if (r.onlyDirs && !r.onlyDirs.some((d) => f.startsWith(d + "/"))) continue;
    const text = fs.readFileSync(path.join(ROOT, f), "utf8");
    const ls = [];
    for (const m of text.matchAll(re)) {
      const line = text.slice(0, m.index).split("\n").length;
      if (r.allowComment) {
        const lineText = text.split("\n")[line - 1] || "";
        if (lineText.includes(r.allowComment)) continue;
      }
      ls.push(line);
    }
    if (ls.length) { rec.files[f] = ls.length; rec.lines[f] = ls; rec.total += ls.length; }
  }
  current[r.id] = rec;
}

if (flag("--init") || flag("--update")) {
  const next = { _about: "Generated by scripts/ux-ratchet.mjs. Counts may only go down. Do not edit by hand.", generated: new Date().toISOString(), rules: {} };
  for (const r of cfg.rules) {
    const cur = current[r.id]; if (!cur) { if (baseline?.rules[r.id]) next.rules[r.id] = baseline.rules[r.id]; continue; }
    const old = baseline?.rules[r.id];
    const entry = { total: 0, files: {} };
    for (const [f, n] of Object.entries(cur.files)) {
      const prev = old?.files?.[f];
      if (flag("--update") && old && n > (prev ?? 0) + credit(r.id, f, current)) {
        console.error(`REFUSED: ${r.id} ${f} has ${n}, baseline allows ${prev ?? 0}. Fix it; the ratchet only goes down.`); process.exit(1);
      }
      entry.files[f] = n; entry.total += n;
    }
    next.rules[r.id] = entry;
  }
  writeJson(basePath, next);
  console.log(`${flag("--init") ? "Created" : "Updated"} ${basePath}.`);
  process.exit(0);
}

if (!baseline) { console.error("ux/baseline.json is missing. Run: node scripts/ux-ratchet.mjs --init (once, on a clean, passing tree)."); process.exit(1); }

const failures = [], improved = [], summary = [];
for (const r of cfg.rules) {
  const cur = current[r.id]; if (!cur) continue;
  const base = baseline.rules[r.id];
  if (!base) { failures.push({ rule: r.id, msg: `rule ${r.id} has no baseline. Run --init on a clean tree or --update.` }); continue; }
  const touchedGuard = [];
  for (const [f, n] of Object.entries(cur.files)) {
    const allowed = (base.files[f] || 0) + credit(r.id, f, current);
    if (n > allowed) failures.push({ rule: r.id, req: r.req, file: f, now: n, allowed, lines: cur.lines[f].slice(-(n - allowed)), fix: r.fix, guarded: guarded.has(f) });
  }
  for (const [f, n] of Object.entries(base.files)) if ((cur.files[f] || 0) < n) improved.push(`${r.id} ${f}: ${n} -> ${cur.files[f] || 0}`);
  summary.push({ id: r.id, req: r.req, title: r.title, target: r.target, baseline: base.total, current: cur.total, worst: Object.entries(cur.files).sort((a, b) => b[1] - a[1]).slice(0, 5), guardedCount: Object.entries(cur.files).filter(([f]) => guarded.has(f)).reduce((a, [, n]) => a + n, 0) });
}

if (flag("--json")) { console.log(JSON.stringify({ ok: !failures.length, summary, failures }, null, 1)); process.exit(failures.length ? 1 : 0); }

if (flag("--report")) {
  console.log("rule | requirement | baseline | now | target | in guarded files");
  for (const s of summary) console.log(`${s.id} | ${s.req} | ${s.baseline} | ${s.current} | ${s.target} | ${s.guardedCount}`);
  console.log("");
  for (const s of summary) if (s.current) console.log(`${s.id} worst files: ${s.worst.map(([f, n]) => `${f} (${n})`).join(", ")}`);
  process.exit(0);
}

const total = summary.reduce((a, s) => a + s.current, 0), totalBase = summary.reduce((a, s) => a + s.baseline, 0);
console.log(`ux-ratchet: ${summary.length} rules, ${files.length} files scanned. Violations now ${total} (baseline ${totalBase}, target 0).`);
if (improved.length) console.log(`\n${improved.length} improvement(s) not yet locked in. Run --update to lock them in:\n  ` + improved.slice(0, 15).join("\n  ") + (improved.length > 15 ? `\n  ... ${improved.length - 15} more` : ""));
if (failures.length) {
  console.log(`\nFAILED: ${failures.length} increase(s):`);
  for (const f of failures.slice(0, 40)) console.log(f.file ? `  - [${f.rule}] ${f.file}: ${f.now} now, ${f.allowed} allowed${f.guarded ? " (GUARDED FILE)" : ""}; lines ${f.lines.join(",")}. ${f.fix}` : `  - [${f.rule}] ${f.msg}`);
  process.exit(1);
}
console.log("OK: no new violations.");
