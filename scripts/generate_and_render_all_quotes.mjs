function pageToSvg(pageOps, width = 595, height = 842) {
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" style="background:#ffffff; font-family: Helvetica, Arial, sans-serif;">\n`;
  
  for (const op of pageOps) {
    if (op.type === "rect") {
      const svgY = height - op.y - op.h;
      const rgb = `rgb(${Math.round(op.color[0]*255)}, ${Math.round(op.color[1]*255)}, ${Math.round(op.color[2]*255)})`;
      svg += `  <rect x="${op.x}" y="${svgY}" width="${op.w}" height="${op.h}" fill="${rgb}" />\n`;
    } else if (op.type === "line") {
      const svgY1 = height - op.y1;
      const svgY2 = height - op.y2;
      const rgb = `rgb(${Math.round(op.color[0]*255)}, ${Math.round(op.color[1]*255)}, ${Math.round(op.color[2]*255)})`;
      svg += `  <line x1="${op.x1}" y1="${svgY1}" x2="${op.x2}" y2="${svgY2}" stroke="${rgb}" stroke-width="${op.width || 0.75}" />\n`;
    } else if (op.type === "text") {
      const svgY = height - op.y;
      const rgb = `rgb(${Math.round(op.color[0]*255)}, ${Math.round(op.color[1]*255)}, ${Math.round(op.color[2]*255)})`;
      const isBold = op.font === "F2";
      const isItalic = op.font === "F3";
      const fontWeight = isBold ? "bold" : "normal";
      const fontStyle = isItalic ? "italic" : "normal";
      // Escape XML characters
      const escapedText = String(op.text)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;");
      svg += `  <text x="${op.x}" y="${svgY}" fill="${rgb}" font-size="${op.size}pt" font-weight="${fontWeight}" font-style="${fontStyle}">${escapedText}</text>\n`;
    }
  }
  
  svg += `</svg>`;
  return svg;
}

async function renderSvgToPng(browser, svgContent, outputPath) {
  const page = await browser.newPage({
    viewport: { width: 1190, height: 1684 }, // 2x A4 points for high resolution
    deviceScaleFactor: 2
  });
  
  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <style>
          body { margin: 0; padding: 20px; background: #e5e7eb; display: flex; justify-content: center; }
          .page-card { box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1), 0 2px 4px -1px rgba(0,0,0,0.06); background: white; }
        </style>
      </head>
      <body>
        <div class="page-card">
          ${svgContent}
        </div>
      </body>
    </html>
  `;
  
  await page.setContent(html);
  const card = await page.$(".page-card");
  await card.screenshot({ path: outputPath });
  await page.close();
}

