#!/usr/bin/env node
// Design-token gate.
//   node scripts/ux-tokens.mjs            check: src/index.css and the prototype match ux/tokens.json, and contrast passes
//   node scripts/ux-tokens.mjs --write    rewrite both files from ux/tokens.json (git diff shows the change)
//   node scripts/ux-tokens.mjs --json     print machine-readable result (used by ux-trace)
// Exit code 1 when anything is wrong. No dependencies.
import fs from "node:fs";
import path from "node:path";
import { ROOT, readJson, contrast } from "./ux-lib.mjs";

const args = process.argv.slice(2);
const WRITE = args.includes("--write");
const JSON_OUT = args.includes("--json");
const spec = readJson("ux/tokens.json");
const BEGIN = "/* UX-TOKENS:BEGIN generated by scripts/ux-tokens.mjs, edit ux/tokens.json */";
const END = "/* UX-TOKENS:END */";

const norm = (v) => String(v).replace(/\/\*.*?\*\//g, "").trim().toLowerCase().replace(/\s+/g, " ").replace(/(^|[ (])0\./g, "$1.").replace(/^\./, ".");

function findBlock(text, selector) {
  const idxs = [];
  let from = 0;
  for (;;) {
    const i = text.indexOf(selector, from);
    if (i < 0) break;
    const open = text.indexOf("{", i);
    const between = text.slice(i + selector.length, open);
    if (/^\s*$/.test(between)) idxs.push([i, open]);
    from = i + selector.length;
  }
  if (!idxs.length) return null;
  const [start, open] = idxs[0];
  let depth = 0, k = open;
  for (; k < text.length; k++) { if (text[k] === "{") depth++; else if (text[k] === "}") { depth--; if (!depth) break; } }
  return { start, open, close: k };
}
const readVar = (body, name) => { const m = new RegExp(`(^|[\\s;{])${name.replace(/[-]/g, "\\-")}\\s*:\\s*([^;]+);`).exec(body); return m ? m[2] : null; };

function wanted(kind, theme) {
  const list = [];
  for (const [id, t] of Object.entries(spec.colors)) {
    const name = kind === "css" ? t.css : t.proto;
    if (name) list.push({ id, name, value: t[theme] });
  }
  if (theme === "light") for (const [id, t] of Object.entries(spec.scale)) {
    const name = kind === "css" ? t.css : t.proto;
    if (name) list.push({ id, name, value: t.value });
  }
  return list;
}

const problems = [];
const report = { files: {}, contrast: [], problems };

for (const [kind, tgt] of Object.entries(spec.targets)) {
  const p = path.join(ROOT, tgt.file);
  if (!fs.existsSync(p)) { report.files[kind] = "missing"; if (kind === "css") problems.push(`${tgt.file} not found`); continue; }
  let text = fs.readFileSync(p, "utf8");
  report.files[kind] = "checked";
  for (const theme of ["light", "dark"]) {
    const sel = theme === "light" ? tgt.lightBlock : tgt.darkBlock;
    const blk = findBlock(text, sel);
    if (!blk) { problems.push(`${tgt.file}: block "${sel}" not found`); continue; }
    let body = text.slice(blk.open + 1, blk.close);
    const missing = [];
    for (const w of wanted(kind, theme)) {
      const have = readVar(body, w.name);
      if (have === null) {
        missing.push(w);
        problems.push(`${tgt.file} [${theme}] ${w.name} is missing (expected ${w.value})`);
      } else if (norm(have) !== norm(w.value)) {
        problems.push(`${tgt.file} [${theme}] ${w.name} = ${norm(have)}, expected ${norm(w.value)}`);
        if (WRITE) body = body.replace(new RegExp(`(^|[\\s;{])(${w.name.replace(/-/g, "\\-")}\\s*:\\s*)([^;]+)(;)`), (_, a, b, _c, d) => `${a}${b}${w.value}${d}`);
      }
    }
    if (WRITE && missing.length) {
      const lines = missing.map((w) => `  ${w.name}: ${w.value};`).join("\n");
      if (body.includes(BEGIN)) body = body.replace(END, `${lines}\n  ${END}`);
      else body = body.replace(/\s*$/, "") + `\n\n  ${BEGIN}\n${lines}\n  ${END}\n`;
    }
    if (WRITE) text = text.slice(0, blk.open + 1) + body + text.slice(blk.close);
  }
  if (WRITE) fs.writeFileSync(p, text);
}

// Contrast (computed from tokens.json itself, so it is checked even if a file is missing)
for (const theme of ["light", "dark"]) {
  for (const rule of spec.contrast) {
    const fgs = rule.fgLiteral ? [{ id: rule.fgLiteral, v: rule.fgLiteral }] : rule.fg.map((id) => ({ id, v: spec.colors[id][theme] }));
    for (const fg of fgs) for (const bgId of rule.bg) {
      const ratio = contrast(fg.v, spec.colors[bgId][theme]);
      const pass = ratio >= rule.min;
      report.contrast.push({ theme, fg: fg.id, bg: bgId, ratio: +ratio.toFixed(2), min: rule.min, pass });
      if (!pass) problems.push(`contrast [${theme}] ${fg.id} on ${bgId} = ${ratio.toFixed(2)}:1, needs ${rule.min}:1 (${rule.why})`);
    }
  }
}

if (JSON_OUT) { console.log(JSON.stringify({ ok: !problems.length, ...report }, null, 1)); process.exit(problems.length && !WRITE ? 1 : 0); }
const failedContrast = report.contrast.filter((c) => !c.pass).length;
console.log(`ux-tokens: ${Object.keys(spec.colors).length} colour tokens x2 themes, ${Object.keys(spec.scale).length} scale tokens, ${report.contrast.length} contrast pairs (${failedContrast} failing).`);
for (const [k, v] of Object.entries(report.files)) console.log(`  ${k}: ${v}`);
if (WRITE) console.log("Wrote files. Re-run without --write to confirm; remaining items below are contrast failures only.");
const left = WRITE ? problems.filter((x) => x.startsWith("contrast")) : problems;
if (left.length) { console.log(`\n${left.length} problem(s):`); left.slice(0, 80).forEach((x) => console.log("  - " + x)); if (left.length > 80) console.log(`  ... ${left.length - 80} more`); process.exit(1); }
console.log("OK: tokens agree and contrast passes.");
